"""Write cloudflare/seed.sql from data/shop.db, in a form Cloudflare D1 accepts.

D1 cannot import a binary .db file and rejects BEGIN/COMMIT, so this writes plain
DROP + CREATE + INSERT statements, parents before children so foreign keys resolve.
Re-running the seed replaces the tables, so it is safe to apply twice.
The notes table is left out: the Worker is read-only.

Usage (from cloudflare/):  python3 scripts/export_d1.py
                           python3 scripts/export_d1.py --db ../data/shop.db --out seed.sql
"""

from __future__ import annotations

import argparse
import sqlite3
from pathlib import Path

HERE = Path(__file__).resolve().parent  # cloudflare/scripts
DEFAULT_DB = HERE.parents[1] / "data" / "shop.db"
DEFAULT_OUT = HERE.parent / "seed.sql"

TABLES = ["categories", "customers", "products", "orders", "order_items", "returns"]  # parents first
ROWS_PER_INSERT = 100  # keeps each statement well under D1's 100 KB statement limit


def sql_value(v: object) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def export(db_path: Path, out_path: Path) -> int:
    db = sqlite3.connect(f"{db_path.resolve().as_uri()}?mode=ro", uri=True)
    lines = ["-- Generated by scripts/export_d1.py from data/shop.db. Do not edit by hand."]
    lines += [f"DROP TABLE IF EXISTS {t};" for t in reversed(TABLES)]
    for t in TABLES:
        (create,) = db.execute("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?", (t,)).fetchone()
        lines.append(create + ";")
    rows_total = 0
    for t in TABLES:  # table names come from the fixed list above, never from input
        cur = db.execute(f"SELECT * FROM {t} ORDER BY 1")
        cols = ", ".join(d[0] for d in cur.description)
        while batch := cur.fetchmany(ROWS_PER_INSERT):
            values = ",\n  ".join("(" + ", ".join(sql_value(v) for v in row) + ")" for row in batch)
            lines.append(f"INSERT INTO {t} ({cols}) VALUES\n  {values};")
            rows_total += len(batch)
    db.close()
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rows_total


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--db", type=Path, default=DEFAULT_DB, help="SQLite file to read (default: ../data/shop.db)")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="SQL file to write (default: seed.sql)")
    args = parser.parse_args()
    rows = export(args.db, args.out)
    print(f"Wrote {rows} rows from {len(TABLES)} tables to {args.out.name}")


if __name__ == "__main__":
    main()
